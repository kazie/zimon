// Command kiwixpin writes internal/kiwix/pins.go: the kiwix-tools release the
// Containerfile's kiwix-serve image is on, and the size and sha-256 of Kiwix's
// archive of it for each platform zimon is released for. zimon serve fetches
// that archive when kiwix-serve isn't installed. Run it from the repository
// (`just pin-kiwix`) after the Containerfile's kiwix-serve changes.
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"maps"
	"net/http"
	"os"
	"regexp"
	"slices"
	"time"

	"github.com/kazie/zimon/internal/kiwix"
)

// platforms names Kiwix's kiwix-tools build for each GOOS/GOARCH zimon is
// released for (.goreleaser.yaml). Kiwix's builds are self-contained: static
// on Linux, and only system libraries on macOS.
var platforms = map[string]string{
	"linux/amd64":  "linux-x86_64",
	"linux/arm64":  "linux-aarch64",
	"darwin/amd64": "macos-x86_64",
	"darwin/arm64": "macos-arm64",
}

var containerImage = regexp.MustCompile(`(?m)^FROM\s+(?:--\S+\s+)*ghcr\.io/kiwix/kiwix-serve:([0-9][^\s@]*)`)

// containerVersion is the kiwix-serve release a Containerfile builds on.
// Kiwix tags its images as it names its archives (3.8.2, or 3.7.0-2 for a
// rebuild).
func containerVersion(containerfile []byte) (string, error) {
	m := containerImage.FindSubmatch(containerfile)
	if m == nil {
		return "", errors.New("no FROM ghcr.io/kiwix/kiwix-serve:VERSION")
	}
	return string(m[1]), nil
}

func main() {
	containerfile := flag.String("containerfile", "Containerfile", "the Containerfile to take the version from")
	out := flag.String("o", "internal/kiwix/pins.go", "the file to write")
	flag.Parse()
	if err := run(*containerfile, *out); err != nil {
		fmt.Fprintln(os.Stderr, "kiwixpin:", err)
		os.Exit(1)
	}
}

func run(containerfile, out string) error {
	data, err := os.ReadFile(containerfile)
	if err != nil {
		return err
	}
	version, err := containerVersion(data)
	if err != nil {
		return fmt.Errorf("%s: %w", containerfile, err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by tools/kiwixpin (just pin-kiwix) from the Containerfile; DO NOT EDIT.

package kiwix

// Version is the kiwix-tools release zimon serve fetches when kiwix-serve
// isn't installed: the container image's.
const Version = %q

// Pins are Kiwix's archives of Version, by GOOS/GOARCH.
var Pins = map[string]Pin{
`, version)
	for _, platform := range slices.Sorted(maps.Keys(platforms)) {
		archive := fmt.Sprintf("kiwix-tools_%s-%s.tar.gz", platforms[platform], version)
		size, sum, err := fetch(ctx, kiwix.DownloadURL+archive)
		if err != nil {
			return fmt.Errorf("%s: %w", archive, err)
		}
		fmt.Fprintf(&b, "\t%q: {Archive: %q, Size: %d, SHA256: %q},\n", platform, archive, size, sum)
		fmt.Fprintf(os.Stderr, "%s: %d bytes\n", archive, size)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// fetch downloads an archive, checks that it holds kiwix-serve, and returns
// its size and sha-256.
func fetch(ctx context.Context, url string) (int64, string, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return 0, "", err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return 0, "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return 0, "", fmt.Errorf("HTTP %s", resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return 0, "", err
	}
	if err := kiwix.CheckArchive(bytes.NewReader(data)); err != nil {
		return 0, "", err
	}
	sum := sha256.Sum256(data)
	return int64(len(data)), hex.EncodeToString(sum[:]), nil
}
